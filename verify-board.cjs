const fs=require('fs');const assert=require('assert');
const html=fs.readFileSync('kds.html','utf8');const js=fs.readFileSync('kds.js','utf8');const home=fs.readFileSync('app.js','utf8');const css=fs.readFileSync('kds.css','utf8');
assert(html.includes('id="board"'),'No hay contenedor Kanban');
assert(html.includes('./kds.js'),'KDS no carga su script');
assert(html.includes('BOARD JIRA · V4'),'Versión incorrecta');
for(const stage of ['Nueva','Preparando','Lista','Entregada'])assert(js.includes(`['${stage}'`),'Falta '+stage);
assert(js.includes('dragstart')&&js.includes("addEventListener('drop'")&&js.includes("addEventListener('pointermove'"),'Falta drag and drop mouse/touch');
assert(js.includes('localStorage.setItem'),'Falta persistencia');
assert(home.includes("location.href='./kds.html'"),'El menú no redirige al tablero');
assert(css.includes('grid-template-columns:repeat(4'),'Falta layout de cuatro columnas');
assert(js.includes('select')&&js.includes('data-next'),'Faltan métodos alternativos de avance');
console.log('OK: tablero 4 columnas, acceso, datos demo, drag/drop, touch y persistencia');
